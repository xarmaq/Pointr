"""Converts selected Iconsax icons (from the MIT-licensed iconsax-react npm package) into
Android vector drawables: res/drawable/ix_<name>_<variant>.xml, white, tinted at runtime.

usage: python iconsax_to_vector.py <path to iconsax-react/package/dist/esm>
"""
import re
import sys
from pathlib import Path

ICONS = ["Setting2", "Keyboard", "Flash", "VolumeHigh", "VolumeSlash", "Moon", "ArrowLeft2", "ArrowRight2",
         "ArrowDown2", "ArrowUp2", "Monitor", "Wifi", "Edit2", "Add", "Logout", "TickCircle", "Trash",
         "TagCross", "Element3", "Radar2", "Mouse", "Timer1"]
VARIANTS = ["Linear", "Bold"]

OUT = Path(__file__).resolve().parent.parent / "android/app/src/main/res/drawable"
ATTR = re.compile(r'(\w+):\s*("([^"]*)"|color|\d+(?:\.\d+)?)')


def snake(name):
    return re.sub(r"(?<=[a-z])(?=[A-Z0-9])|(?<=[0-9])(?=[A-Z])", "_", name).lower()


def variant_body(src, variant):
    m = re.search(r"var %s = function %s\(_ref\d*\) \{(.*?)\n\};" % (variant, variant), src, re.S)
    return m.group(1) if m else None


def paths(body):
    for m in re.finditer(r'createElement\("path", \{(.*?)\}\)', body, re.S):
        attrs = {}
        for a in ATTR.finditer(m.group(1)):
            attrs[a.group(1)] = a.group(3) if a.group(3) is not None else a.group(2)
        yield attrs


def to_xml(items):
    out = ['<?xml version="1.0" encoding="utf-8"?>',
           '<!-- Iconsax (iconsax-react, MIT). Generated by tools/iconsax_to_vector.py -->',
           '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
           '    android:width="24dp" android:height="24dp" android:viewportWidth="24" android:viewportHeight="24">']
    for a in items:
        line = [f'    <path android:pathData="{a["d"]}"']
        if a.get("fill") == "color":
            line.append('android:fillColor="#FFFFFFFF"')
        if a.get("stroke") == "color":
            line.append('android:strokeColor="#FFFFFFFF"')
            line.append(f'android:strokeWidth="{a.get("strokeWidth", "1.5")}"')
            if "strokeLinecap" in a:
                line.append(f'android:strokeLineCap="{a["strokeLinecap"]}"')
            if "strokeLinejoin" in a:
                line.append(f'android:strokeLineJoin="{a["strokeLinejoin"]}"')
            if "strokeMiterlimit" in a:
                line.append(f'android:strokeMiterLimit="{a["strokeMiterlimit"]}"')
        if "opacity" in a:
            alpha = a["opacity"]
            line.append(f'android:fillAlpha="{alpha}" android:strokeAlpha="{alpha}"')
        out.append(" ".join(line) + " />")
    out.append("</vector>")
    return "\n".join(out) + "\n"


def main(src_dir):
    OUT.mkdir(parents=True, exist_ok=True)
    for icon in ICONS:
        src = (Path(src_dir) / f"{icon}.js").read_text(encoding="utf-8")
        for v in VARIANTS:
            body = variant_body(src, v)
            items = [a for a in paths(body) if "d" in a] if body else []
            if not items:
                print(f"skip {icon}/{v}")
                continue
            (OUT / f"ix_{snake(icon)}_{v.lower()}.xml").write_text(to_xml(items), encoding="utf-8")
    print("done")


if __name__ == "__main__":
    main(sys.argv[1])
